const fs = require('fs');
const assert = require('assert');
const root = require('path').join(__dirname, '..');
const read = (path) => fs.readFileSync(require('path').join(root, path), 'utf8');
const routes = read('public/index.php');
const controller = read('app/controllers/IniciativasApiController.php');
const service = read('app/services/IniciativaAcompanhamentoService.php');
const evidence = read('app/services/IniciativaEvidenciaService.php');
const view = read('views/frontend/iniciativas.php');
const approval = read('views/frontend/iniciativas-homologacao.php');
const consolidation = read('views/frontend/iniciativas-consolidacao.php');
const js = read('assets/js/iniciativas.js');

assert(routes.includes("/api/iniciativas-acompanhamentos/{id}/submeter"), 'rota explícita de submissão deve existir');
assert(routes.includes("/api/iniciativas-homologacoes/{id}/{action}"), 'rotas de homologação devem existir');
assert(routes.includes("/api/iniciativas-consolidacao/{id}"), 'rota de consolidação deve existir');
assert((controller.match(/Auth::requireCsrf\(\)/g) || []).length >= 8, 'todas as mutações devem exigir CSRF');
assert(service.includes('AccessPolicy::initiativeScopeAllows'), 'serviço deve validar escopo persistido');
assert(service.includes('assertInitiativeMutable'), 'salvar e submeter devem aplicar governança central');
assert(service.includes("'acompanhamento_submetido'"), 'submissão deve ser auditada');
assert(evidence.includes('UPLOAD_PATH.\'/iniciativas/\''), 'evidências devem ficar na subárvore privada de iniciativas');
assert(evidence.includes('evidencia_iniciativa_anexada') && evidence.includes('evidencia_iniciativa_removida'), 'evidências devem ser auditadas');
assert(view.includes('Dados') || view.includes('trackingSnapshot'), 'tela deve exibir snapshot somente leitura');
assert(js.includes('Marcos e Entregas') && js.includes('Próximos Passos') && js.includes('Frentes / Projetos / Ações'), 'tela deve separar os tipos de item');
assert(approval.includes('Homologar') && approval.includes('Devolver para ajuste'), 'tela de análise deve expor decisões');
assert(consolidation.includes('Informação homologada') && consolidation.includes('Conteúdo executivo CA'), 'consolidação deve separar origem e síntese');
assert(js.includes('textContent') && !js.includes('alert('), 'renderização deve evitar HTML livre e alertas');
assert.strictEqual(read('assets/js/iniciativas.js'), read('public/assets/js/iniciativas.js'), 'JavaScript duplicado deve ser byte a byte idêntico');
assert.strictEqual(read('assets/js/app.js'), read('public/assets/js/app.js'), 'app.js duplicado deve ser idêntico');
assert.strictEqual(read('assets/js/auth.js'), read('public/assets/js/auth.js'), 'auth.js duplicado deve ser idêntico');
assert.strictEqual(read('assets/css/styles.css'), read('public/assets/css/styles.css'), 'CSS duplicado deve ser idêntico');
console.log('Rotas, CSRF, UI, evidências e assets duplicados de iniciativas OK');
